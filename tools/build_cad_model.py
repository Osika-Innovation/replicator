def title(slug):
    words = []
    for w in slug.split('-'):
        words.append(RENAME.get(w, w))
    t = ' '.join(words)
    return t[:1].upper() + t[1:]


def parse(obj_path):
    verts, parts, cur = [], collections.OrderedDict(), None
    for line in obj_path.read_text().splitlines():
        if line.startswith('v '):
            verts.append([float(x) for x in line.split()[1:4]])
        elif line.startswith('o '):
            cur = line[2:].strip()
            parts[cur] = {'material': None, 'faces': []}
        elif line.startswith('usemtl '):
            parts[cur]['material'] = line.split()[1]
        elif line.startswith('f '):
            idx = [int(tok.split('/')[0]) - 1 for tok in line.split()[1:]]
            for k in range(1, len(idx) - 1):  # fan-triangulate
                parts[cur]['faces'].append((idx[0], idx[k], idx[k + 1]))
    return np.array(verts, dtype=np.float64), parts


def materials(mtl_path):
    out, name = {}, None
    for line in mtl_path.read_text().splitlines():
        t = line.split()
        if not t:
            continue
        if t[0] == 'newmtl':
            name = t[1]; out[name] = {'color': [0.5, 0.5, 0.5], 'opacity': 1.0}
        elif t[0] == 'Kd' and name:
            out[name]['color'] = [round(float(x), 3) for x in t[1:4]]
        elif t[0] == 'd' and name:
            out[name]['opacity'] = round(float(t[1]), 3)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--from', dest='source', type=Path, default=DEFAULT)
    args = ap.parse_args()
    cad = args.source.resolve() / 'cad/desktop-replicator'
    verts, parts = parse(cad / 'desktop_replicator.obj')
    mats = materials(cad / 'desktop_replicator.mtl')
    header = (cad / 'desktop_replicator.obj').read_text().splitlines()[0].lstrip('# ').strip()

    positions, indices, out_parts = [], [], []
    vbase = 0
    for key, p in parts.items():
        asm, slug = key.split('__', 1)
        if asm not in ASSEMBLIES:
            raise SystemExit(f'unknown assembly {asm!r}: add it to ASSEMBLIES in {Path(__file__).name}')
        faces = np.array(p['faces'], dtype=np.int64)
        used = np.unique(faces)
        remap = np.zeros(len(verts), dtype=np.int64)
        remap[used] = np.arange(len(used))
        pv = verts[used]
        lo, hi = pv.min(0), pv.max(0)
        positions.append(pv.astype(np.float32))
        indices.append((remap[faces] + vbase).astype(np.uint32))
        ds, guide, text = ASSEMBLIES[asm][2], ASSEMBLIES[asm][3], None
        for pattern, d, g, t in PART_RULES:
            if re.search(pattern, slug):
                ds, guide, text = d, g, t
                break
        out_parts.append({
            'id': key, 'assembly': asm, 'name': title(slug), 'material': MATERIAL_LABEL.get(p['material'], p['material']),
            'matKey': p['material'], 'bbox': [round(float(v), 1) for v in (*lo, *hi)],
            'vert': [vbase, len(used)], 'tri': [sum(len(i) for i in indices[:-1]), len(faces)],
            'subsystem': DS[ds][0], 'subsystemLabel': DS[ds][1], 'guide': GUIDE[guide][0], 'guideLabel': GUIDE[guide][1],
            'text': text})
        vbase += len(used)

    pos = np.concatenate(positions)
    idx = np.concatenate(indices).ravel()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / 'desktop.bin').write_bytes(pos.tobytes() + idx.tobytes())
    lo, hi = pos.min(0), pos.max(0)
    model = {
        'schema': 'etherworks-cad/1', 'name': 'Desktop Replicator', 'revision': 'Rev S, default build with the M1 cassette',
        'source': 'fieldc desktop export', 'exportHeader': header,
        'units': 'mm', 'frame': 'z up, floor at z = 0, front at +x',
        'counts': {'vertices': int(len(pos)), 'indices': int(len(idx)), 'parts': len(out_parts)},
        'bounds': [round(float(v), 1) for v in (*lo, *hi)],
        'assemblies': [{'id': k, 'title': v[0], 'summary': v[1], 'subsystem': DS[v[2]][0], 'subsystemLabel': DS[v[2]][1],
                        'guide': GUIDE[v[3]][0], 'guideLabel': GUIDE[v[3]][1], 'explode': list(v[4])} for k, v in ASSEMBLIES.items()],
        'materials': mats,
        'parts': out_parts,
    }
    (OUT / 'desktop.json').write_text(json.dumps(model, separators=(',', ':'), ensure_ascii=False) + '\n')
    print(f"{len(out_parts)} parts, {len(pos)} vertices, {len(idx) // 3} triangles; "
          f"desktop.bin {(OUT / 'desktop.bin').stat().st_size // 1024} kB, desktop.json {(OUT / 'desktop.json').stat().st_size // 1024} kB")
    unmatched = [p['id'] for p in out_parts if p['text'] is None]
    print(f'{len(unmatched)} parts use their assembly description')


if __name__ == '__main__':
    main()
