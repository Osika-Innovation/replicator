import Foundation

/// The manufacturing pack: what has to be made, what has to be bought, how
/// the plates are driven, and what cannot be built from this model yet.
/// Generated from the solid model (`fieldc cad pack`) — edit the design.
public extension CADExport {

    /// How a part is made, from what it is made of and what it is.
    static func process(_ p: CADPart) -> String {
        let n = p.name
        switch p.material {
        case .placeholder: return "not specified (envelope only)"
        case .transmitter: return "bought: custom-tuned open-type transmitter"
        case .pzt: return "bought: PZT-8 disc, silvered"
        case .fr4:
            return n.hasPrefix("wiring board") ? "PCB, routed outline and slots" : "PCB assembly"
        case .glass: return "bought: bent laminated glass, coated"
        case .photonic: return "bought: laminated glass tile — the hologram layer is OPEN"
        case .emissive: return "bought: LED strip"
        case .ceramic: return "ceramic additive (SLA) — the gyroid lattice itself is not modelled"
        case .copper:
            return n.hasPrefix("winding") ? "wound on its former, then potted" : "turned from copper bar"
        case .bronze: return "wound on its former, then potted"
        case .former: return "machined from glass-filled PEEK, two halves"
        case .polymer:
            return n.hasPrefix("element") ? "injection moulded (machined for a prototype)" : "turned from POM rod"
        case .anodized, .columnMetal, .plateMetal:
            if n.hasPrefix("face plate") { return "CNC milled from Al 6082 plate: holes drilled and reamed, slots milled, both faces skimmed" }
            if n.contains("tube") || n.contains("band") || n.contains("liner") || n == "crown" { return "rolled and welded Al 6063 tube, turned at the ends, anodized" }
            if n.contains("column") { return "extruded Al 6063, cut to length, anodized" }
            return "CNC turned from Al, anodized"
        }
    }

    /// A part's name with the face, assembly and serial stripped, so the
    /// same part on four faces is one row.
    static func family(_ name: String) -> String {
        var words = name.split(separator: " ").map(String.init)
        let drop: Set<String> = ["top", "mid-up", "mid-down", "deck", "middle", "lower", "upper", "CW", "CCW", "(feed", "A)", "B)"]
        words.removeAll { drop.contains($0) || Double($0) != nil || $0.contains(".") && Double($0.split(separator: ".").last ?? "") != nil }
        return words.joined(separator: " ")
    }

    static func manufacturingMarkdown(_ model: RH1Model, medium: Medium) -> String {
        let d = model.design
        var s = "# RH-1 manufacturing pack (generated)\n\n"
        s += "Generated by `fieldc cad pack` from `RH1Design` — edit the design, not this file.\n"
        s += "It lists what the solid model knows. A part marked *assumed* is a sized choice no paper commits to;\n"
        s += "an *envelope* is a volume reserved for something not designed yet.\n\n"

        // ---- readiness ----
        var byRegister: [String: Int] = [:]
        for p in model.parts { byRegister[p.material == .placeholder ? "envelope" : p.register.rawValue, default: 0] += 1 }
        s += "## Where the model stands\n\n| register | parts |\n|---|---:|\n"
        for k in ["committed", "site", "derived", "resolved", "assumed", "envelope"] where byRegister[k] != nil {
            s += "| \(k) | \(byRegister[k]!) |\n"
        }
        s += "\n"

        // ---- made and bought parts, grouped ----
        struct Group { var count = 0; var mass = 0.0; var material = ""; var process = ""; var register = ""; var note = "" }
        var order: [String] = [], groups: [String: Group] = [:]
        for p in model.parts {
            let key = family(p.name) + "|" + p.material.rawValue
            if groups[key] == nil { order.append(key) }
            var g = groups[key] ?? Group()
            g.count += 1; g.mass += p.massKg ?? 0
            g.material = p.material.label; g.process = process(p); g.register = p.register.rawValue; g.note = p.note
            groups[key] = g
        }
        func table(_ title: String, _ keep: (Group) -> Bool) {
            s += "## \(title)\n\n| part | qty | material | how | kg each | register |\n|---|---:|---|---|---:|---|\n"
            for key in order {
                let g = groups[key]!
                guard keep(g) else { continue }
                s += "| \(key.split(separator: "|")[0]) | \(g.count) | \(g.material) | \(g.process) | "
                    + String(format: "%.3f", g.mass / Double(g.count)) + " | \(g.register) |\n"
            }
            s += "\n"
        }
        table("Made parts") { !$0.process.hasPrefix("bought") && !$0.process.hasPrefix("not specified") && !$0.process.hasPrefix("PCB") }
        table("Boards") { $0.process.hasPrefix("PCB") }
        table("Bought parts in the solid model") { $0.process.hasPrefix("bought") }

        // ---- the elements, tone by tone ----
        if d.resonantElements {
            let faces = d.faces.count
            s += "## The elements\n\n"
            s += "Each face carries \(d.elementCount) resonant transmitters, each tuned to one of \(d.elementTones.count) tones and driven by its own channel.\n"
            s += "They are the bought 40 kHz open-type transmitter (Ø\(Int(d.elementFaceAt40k)) mm) scaled to each tone. "
            s += "**No such part has been built or measured at these tones**: the face velocity it reaches is assumed equal to the 40 kHz part's.\n\n"
            s += "| tone kHz | face Ø mm | can Ø × h mm | drive V rms (max) | face velocity m/s | per up face | per down face | machine |\n|---:|---:|---|---:|---:|---:|---:|---:|\n"
            var totalPower = 0.0
            for (q, f) in d.elementTones.enumerated() {
                let spec = ElementSpec.scaled(to: f, medium: medium)
                let up = model.pattern.elements.filter { $0.tone == q }.count
                let down = model.patternDown.elements.filter { $0.tone == q }.count
                let dia = 2 * spec.radius * 1000
                let pa = spec.acousticPower(velocity: spec.maxVelocity(at: f), at: f, medium: medium)
                totalPower += Double(up + down) * pa / spec.efficiency
                s += String(format: "| %.1f | %.1f | %.1f × %.1f | %.1f | %.2f | %d | %d | %d |\n", f / 1000, dia, dia,
                            min(d.elementCanAspect * dia, d.facePlateThickness - 1), spec.maxVolts, spec.maxVelocity(at: f),
                            up, down, (up + down) * faces / 2)
            }
            let n = d.elementCount
            s += "\n## Drive electronics, per face\n\n"
            s += "| item | qty | note |\n|---|---:|---|\n"
            s += "| drive channels | \(n) | one per element: a square wave at the element's tone, phase set by timing |\n"
            s += "| two-channel gate drivers (SOIC-8 class) | \((n + 1) / 2) | 20 V rail at most; each element is a ~2 nF load |\n"
            s += "| 8-bit shift registers | \((n + 7) / 8) | the phase pattern, clocked from the controller |\n"
            s += "| wiring board | 1 | \(d.wiringBoardLayers) layers, \(String(format: "%.1f", d.wiringBoardThickness)) mm, on the plate's back |\n"
            s += "| ring boards in the rim annulus | \(Int(((d.rimDepthTo - d.rimDepthFrom) / d.rimBoardPitch).rounded(.down))) | carry the drivers and registers |\n"
            s += String(format: "\nEvery element of the two build-chamber faces at its full drive: about %.0f W electrical, of which %.0f W is heat in the plates (efficiency %.0f %%, assumed).\n\n",
                        totalPower, totalPower * (1 - ElementSpec.scaled(to: d.elementTones[0], medium: medium).efficiency),
                        100 * ElementSpec.scaled(to: d.elementTones[0], medium: medium).efficiency)
        }

        // ---- assembly ----
        s += "## Assembly order\n\n"
        s += "1. Each plate stack, face down on a flat: press the element carriers and transmitters into the face plate, flush with the face; lay the wiring board on the plate's back and solder every pin; fit the carrier ring.\n"
        s += d.rearStack ? "2. Behind it: the gyroid horn, the copper cone and the three throat piezos; then the rim electronics' ring boards.\n"
                         : "2. Behind it: the rim electronics' ring boards, plugged to the wiring board. Nothing else: the horn, cone and throat piezos of the micro-horn face are not part of this configuration.\n"
        s += "3. Wind each torus former (inner layer, then outer, opposite hand) and pot it; seat it on its setback behind the plate.\n"
        s += "4. Stack from the base: bottom closure, base envelopes, deck plate stack, storage liner, middle assembly (two stacks about one torus), rear glass and the seven columns, top plate stack, top band, crown.\n"
        s += "5. Hang the front glass on its two V-tracks; check it turns through 180°.\n"
        s += "6. Calibrate: with the chamber empty, play each element alone and record every other element (`MachineBackend.calibrate`); the measured gains and phases replace the drawing's.\n\n"

        // ---- what is missing ----
        s += "## Not buildable from this pack yet\n\n"
        for p in model.parts where p.material == .placeholder { s += "* **\(p.name)** — an envelope only. \(p.note)\n" }
        s += "* The gyroid lattice, the photonic tiles' hologram layer and write projector, gaskets, fasteners, the door interlock, cabling beyond the wiring boards, and the controller are not modelled.\n"
        s += "* No element has been measured." + (d.rearStack ? "" : " The space behind each plate that the horn, cone and throat piezos held is empty; what cools the plate (its elements' heat) is not designed.") + "\n"
        return s
    }
}
